// Função para imprimir um número várias vezes
function repetidor10(number, times) {
    for (let i = 0; i < times; i++) {
        console.log(number);
    }
}

// Função para concatenar e exibir um nome com um sufixo
function concatenar(name, suffix) {
    console.log(name + suffix);
}

// Uso das funções
const x = 10;
repetidor10(x, 10);

let name = "pedro";
concatenar(name, "2");



